// js/suite.js - Suite Teil - 9 steht wie 1 - Atmen ein - 9er
const SUITE = { 
  atmen(){ return "ein"; }, // 3 oben erster
  steht(){ return "wie 1"; } // 9 steht wie 1
}

// js/sys.js - Sys Teil - 9 zu 81 - Wurzeln aus - 9er  
const SYS = { 
  wurzeln(){ return "aus"; }, // 81 unten letzter
  zu(){ return "9 zu 81 = 9*9"; } // 9 zu 81
}

// zusammen = ein- und ausatmen = Wurzeln = 3er aber 9er
// 3 oben erster = SUITE ein
// 9 mitte = SUITE + SYS zusammen = steht wie 1
// 81 unten letzter = SYS aus
